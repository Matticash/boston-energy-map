"""Join MassCEC small-solar totals to MassGIS town boundaries -> data/towns.js

Usage: python -I build_towns.py <PTS xlsx> <towns geojson> <out towns.js>

- Small solar = systems under 1,000 kW-DC (bigger ones are already on the map from EIA-860).
- Capacity is DC (panel rating); EIA's site figures are AC.
- MassCEC data is as of Jan 14, 2025 and undercounts 2022-2024 installs (its own warning).
"""
import sys, json, pandas as pd

pts_path, geo_path, out = sys.argv[1], sys.argv[2], sys.argv[3]

df = pd.read_excel(pts_path, sheet_name="PvinPTSwebsite", header=10)
df = df.rename(columns={"Capacity \n(DC, kW)": "kw"})
df["kw"] = pd.to_numeric(df["kw"], errors="coerce")
df = df[df["kw"] < 1000]
df["town"] = df["City"].astype(str).str.strip().str.upper()
df["home"] = df["Facility Type"].astype(str).str.startswith("Residential")
by_town = df.groupby("town").agg(kw=("kw", "sum"), n=("kw", "size"), homes=("home", "sum"))

geo = json.load(open(geo_path))
unmatched = []
for f in geo["features"]:
    p = f["properties"]
    name = p["TOWN"]
    key = {"MANCHESTER-BY-THE-SEA": "MANCHESTER"}.get(name, name)  # MassCEC uses the short name
    row = by_town.loc[key] if key in by_town.index else None
    if row is None:
        unmatched.append(name)
    kw = float(row.kw) if row is not None else 0.0
    pop = int(p.get("POP2020") or 0)
    f["properties"] = {
        "town": name.title().replace("-By-The-", "-by-the-"),
        "pop": pop,
        "smallSolarMW": round(kw / 1000, 2),
        "systems": int(row.n) if row is not None else 0,
        "homeSystems": int(row.homes) if row is not None else 0,
        "wattsPerPerson": round(kw * 1000 / pop) if pop else None,
    }

header = """// Small solar (systems under 1 MW) by Massachusetts town. GENERATED by tools/build_towns.py.
// Solar: MassCEC Production Tracking System, "Solar PV Systems in MA as of Jan 2025"
//   https://www.masscec.com/production-tracking-system-pts  (capacity in kW-DC; undercounts 2022-2024)
// Boundaries and 2020 population: MassGIS Municipalities
//   https://www.mass.gov/info-details/massgis-data-municipalities
"""
with open(out, "w") as fh:
    fh.write(header + "window.TOWNS = " + json.dumps(geo, separators=(",", ":")) + ";\n")

tot = sum(f["properties"]["smallSolarMW"] for f in geo["features"])
print(f"{len(geo['features'])} towns, {tot:,.0f} MW-DC small solar; unmatched: {unmatched}")
top = sorted(geo["features"], key=lambda f: -(f["properties"]["wattsPerPerson"] or 0))[:8]
print("Top W/person:", [(f["properties"]["town"], f["properties"]["wattsPerPerson"]) for f in top])
bos = [f["properties"] for f in geo["features"] if f["properties"]["town"] in ("Boston", "Newton", "Cambridge", "Brookline")]
print(bos)
