"""Turn the EIA-860 study-area extract into the map's data/sites.js.
Usage: python -I build_sites.py <sites_in_box csv> <out sites.js>
Leaves out fossil plants and trash-to-energy (Matt's call, 2026-11-22).
"""
import sys, json, pandas as pd

src, out = sys.argv[1], sys.argv[2]
df = pd.read_csv(src)

KEEP = {
    "solar": "solar",
    "wind": "wind",
    "hydro": "hydro",
    "other biomass": "biomass",
    "landfill gas": "landfill gas",
    "battery (storage)": "battery",
}
df = df[df["category"].isin(KEEP)].copy()
df["type"] = df["category"].map(KEEP)

def title(s):
    s = str(s)
    return s if any(c.islower() for c in s) else s.title()

sites = []
for r in df.sort_values("mw", ascending=False).itertuples():
    sites.append({
        "name": title(r._2),          # Plant Name
        "city": title(r.City),
        "state": r.State,
        "type": r.type,
        "stage": r.stage,             # operating | proposed
        "mw": round(float(r.mw), 2),
        "year": None if pd.isna(r.first_year) else int(r.first_year),
        "lat": round(float(r.Latitude), 5),
        "lng": round(float(r.Longitude), 5),
        "eiaPlantCode": int(r._1),
    })

header = """// Energy sites shown on the map. GENERATED by build_sites.py, don't hand-edit.
// Source: U.S. Energy Information Administration, Form EIA-860 (2025 data),
//   https://www.eia.gov/electricity/data/eia860/
// Covers plants of 1 MW or more inside the study area. Rooftop solar under
// 1 MW is not included. Fossil plants and trash-to-energy are left out.
// stage: "operating" or "proposed". year: first year online (or planned).
"""
with open(out, "w") as f:
    f.write(header + "window.SITES = " + json.dumps(sites, indent=1) + ";\n")
print(len(sites), "sites written;", df.groupby(["type", "stage"]).size().to_dict())
